rows = []
for ch in order:
    g = G.get(ch, "|".join(["....."] * 7))
    r = g.split("|")
    assert len(r) == 7 and all(len(x) == 5 for x in r), ch
    rows.append([int(x.replace("#", "1").replace(".", "0"), 2) for x in r])
